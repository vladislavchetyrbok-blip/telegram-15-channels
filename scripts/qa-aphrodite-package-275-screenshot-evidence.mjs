async function ensureServer(timeoutMs) {
  const host = "127.0.0.1";
  const port = await findFreePort(3200);
  const baseUrl = `http://${host}:${port}`;
  const nextCli = path.join(ROOT, "node_modules", "next", "dist", "bin", "next");
  if (!fs.existsSync(nextCli)) throw new Error(`Next CLI was not found at ${nextCli}.`);

  const hasProductionBuild = fs.existsSync(path.join(ROOT, ".next", "BUILD_ID"));
  const serverArgs = hasProductionBuild
    ? [nextCli, "start", "-H", host, "-p", String(port)]
    : [nextCli, "dev", "-H", host, "-p", String(port)];

  const child = spawn(process.execPath, serverArgs, {
    cwd: ROOT,
    env: { ...process.env, BROWSER: "none" },
    stdio: ["ignore", "pipe", "pipe"],
    windowsHide: true,
  });
  startedProcesses.push(child);

  let output = "";
  child.stdout?.on("data", (chunk) => {
    output = (output + chunk.toString()).slice(-4000);
  });
  child.stderr?.on("data", (chunk) => {
    output = (output + chunk.toString()).slice(-4000);
  });

  await waitFor(async () => {
    if (child.exitCode !== null) throw new Error(`Next server exited early.\n${output}`);
    return (await probeHttpStatus(`${baseUrl}/miniapp`)) === 200;
  }, `Next server did not become ready at ${baseUrl}.\n${output}`, timeoutMs, 1000);

  return { url: baseUrl };
}

