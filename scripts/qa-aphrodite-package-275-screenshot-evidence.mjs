async function main() {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });

  if (!options.validateOnly) {
    prepareOutputDirectory();
    const server = await ensureServer(DEFAULT_TIMEOUT_MS);
    const browserPath = findBrowserExecutable();
    if (!browserPath || typeof WebSocket !== "function") {
      throw new Error("Chrome/Edge with CDP and global WebSocket are required to generate Package 275 screenshots.");
    }

    const browser = await launchBrowser(browserPath);
    const page = await createPage(browser.debugPort);
    const client = await CdpClient.connect(page.webSocketDebuggerUrl);
    await enablePageDomains(client);

    try {
      await captureDirectScreens(client, server.url);
    } finally {
      await client.close();
    }

    await runSmokeScreenshotCapture();
    copySmokeScreenshot("compatibility-result.png", "390-compatibility-result.png");
    copySmokeScreenshot("birth-matrix.png", "390-birth-matrix-result.png");
    copySmokeScreenshot("tarot-spread.png", "390-mystic-cards-result.png");
    fs.rmSync(SMOKE_DIR, { recursive: true, force: true });
    writeReadme();
  }

  const validation = validateScreenshots();
  writeChecksumReport(validation);

  if (validation.missing.length || validation.duplicates.length) {
    console.error(`Missing screenshots: ${validation.missing.join(", ") || "none"}`);
    console.error(`Duplicate groups: ${validation.duplicates.length}`);
    process.exit(1);
  }

  console.log("Package 275 screenshot evidence QA: PASS");
  console.log(`Screenshots: ${validation.files.length}`);
  console.log(`Duplicate hash groups: ${validation.duplicates.length}`);
}

