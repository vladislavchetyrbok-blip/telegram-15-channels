function validateScreenshots() {
  const required = new Set(scenarioRows.map((item) => item.filename));
  const pngs = fs.existsSync(OUTPUT_DIR)
    ? fs.readdirSync(OUTPUT_DIR).filter((file) => file.endsWith(".png")).sort()
    : [];
  const missing = [...required].filter((file) => !pngs.includes(file)).sort();
  const files = pngs.map((file) => {
    const absolutePath = path.join(OUTPUT_DIR, file);
    const buffer = fs.readFileSync(absolutePath);
    return {
      file,
      bytes: buffer.length,
      sha256: crypto.createHash("sha256").update(buffer).digest("hex"),
    };
  });

  const groups = new Map();
  for (const item of files) {
    if (!groups.has(item.sha256)) groups.set(item.sha256, []);
    groups.get(item.sha256).push(item);
  }

  const duplicates = [...groups.entries()]
    .filter(([, items]) => items.length > 1)
    .map(([sha256, items]) => ({ sha256, files: items.map((item) => item.file).sort() }))
    .sort((a, b) => a.sha256.localeCompare(b.sha256));

  return { files, missing, duplicates };
}

function writeChecksumReport(validation) {
  fs.writeFileSync(CHECKSUMS_PATH, JSON.stringify({ generatedAt: new Date().toISOString(), ...validation }, null, 2), "utf8");

  const lines = [
    "# Package 275 Duplicate Hash Report",
    "",
    `PNG files checked: ${validation.files.length}`,
    `Missing required screenshots: ${validation.missing.length ? validation.missing.join(", ") : "none"}`,
    `Duplicate hash groups: ${validation.duplicates.length}`,
    "",
  ];

  if (validation.duplicates.length) {
    for (const group of validation.duplicates) {
      lines.push(`- ${group.sha256}: ${group.files.join(", ")}`);
    }
  } else {
    lines.push("No duplicate PNG hashes found.");
  }

  lines.push("");
  fs.writeFileSync(DUPLICATE_REPORT_PATH, lines.join("\n"), "utf8");
}

