const ZODIAC_GUIDANCE_SLUGS = Object.keys(ZODIAC_DAILY_GUIDANCE);

const GUIDANCE_FIELDS = ["adviceOfDay", "shouldDoToday", "shouldAvoidToday"];

function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function getDateOrdinal(date) {
  if (!date) return 0;
  const [year, month, day] = String(date).split("-").map(Number);
  if (!year || !month || !day) return 0;
  return Math.floor(Date.UTC(year, month - 1, day) / 86_400_000);
}

function getSlugOffset(slug) {
  const index = ZODIAC_GUIDANCE_SLUGS.indexOf(slug);
  return index === -1 ? 0 : index;
}

export function getZodiacDailyGuidance(slug, date) {
  const variants = ZODIAC_DAILY_GUIDANCE[slug] ?? ZODIAC_DAILY_GUIDANCE["zodiac-general"];
  const index = (getDateOrdinal(date) + getSlugOffset(slug)) % variants.length;
  return { ...variants[index] };
}

export function renderZodiacDailyGuidanceBlock(guidance) {
  return [
    "<b>Главное на день:</b>",
    `💡 <b>Совет дня:</b> ${escapeHtml(guidance.adviceOfDay)}`,
    `✅ <b>Стоит сделать:</b> ${escapeHtml(guidance.shouldDoToday)}`,
    `⚠️ <b>Лучше избегать:</b> ${escapeHtml(guidance.shouldAvoidToday)}`,
  ].join("\n");
}

export function validateZodiacDailyGuidanceFields(post, maxLength = ZODIAC_DAILY_GUIDANCE_MAX_LENGTH) {
  const issues = [];
  for (const field of GUIDANCE_FIELDS) {
    const value = String(post?.[field] ?? "").trim();
    if (!value) {
      issues.push(`${field} is missing or empty`);
      continue;
    }
    if (value.length > maxLength) {
      issues.push(`${field} is too long: ${value.length}/${maxLength}`);
    }
  }
  return issues;
}

export function validateZodiacDailyGuidanceText(post) {
  const issues = [];
  const text = String(post?.text ?? "");
  const expectedLabels = [
    "<b>Главное на день:</b>",
    "💡 <b>Совет дня:</b>",
    "✅ <b>Стоит сделать:</b>",
    "⚠️ <b>Лучше избегать:</b>",
    "<b>Гороскоп:</b>",
  ];

  for (const label of expectedLabels) {
    if (!text.includes(label)) {
      issues.push(`text is missing guidance label: ${label}`);
    }
  }

  const guidanceIndex = text.indexOf("<b>Главное на день:</b>");
  const horoscopeIndex = text.indexOf("<b>Гороскоп:</b>");
  if (guidanceIndex === -1 || horoscopeIndex === -1 || guidanceIndex > horoscopeIndex) {
    issues.push("guidance block must appear before <b>Гороскоп:</b>");
  }

  for (const field of GUIDANCE_FIELDS) {
    const value = String(post?.[field] ?? "").trim();
    if (value && !text.includes(escapeHtml(value))) {
      issues.push(`text does not include ${field}`);
    }
  }

  return issues;
}

export function validateZodiacDailyGuidanceUniqueness(posts) {
  const issues = [];
  const postsByDate = new Map();

  for (const post of posts || []) {
    if (!post || post.channelId === "zodiac-general") continue;
    const date = post.date || "unknown-date";
    if (!postsByDate.has(date)) postsByDate.set(date, []);
    postsByDate.get(date).push(post);
  }

  for (const [date, dayPosts] of postsByDate.entries()) {
    for (const field of GUIDANCE_FIELDS) {
      const values = new Map();
      for (const post of dayPosts) {
        const value = String(post[field] ?? "").trim().toLocaleLowerCase("ru-RU");
        if (!value) continue;
        if (!values.has(value)) values.set(value, []);
        values.get(value).push(post.channelId || "unknown");
      }

      for (const [value, slugs] of values.entries()) {
        if (slugs.length > 1) {
          issues.push(`${date}: ${field} is reused by ${slugs.join(", ")}: ${value}`);
        }
      }
    }
  }

  return issues;
}

export function validateZodiacDailyPostGuidance(post, maxLength = ZODIAC_DAILY_GUIDANCE_MAX_LENGTH) {
  return [
    ...validateZodiacDailyGuidanceFields(post, maxLength),
    ...validateZodiacDailyGuidanceText(post),
  ];
}
